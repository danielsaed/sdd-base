#!/usr/bin/env node
// Generates OpenCode's config from Claude Code's, so both tools run the SAME workflow and
// every fact keeps ONE home (AGENTS.md, «One fact, ONE home»):
//
//   source (edit this)                 generated (never by hand)
//   .claude/agents/<name>.md       →   .opencode/agents/<name>.md (+ model variants, below)
//   .claude/settings.json  deny    →   opencode.json  "permission"
//   .mcp.json              servers →   opencode.json  "mcp"
//
// Shared as they are, nothing to generate: AGENTS.md and .claude/skills/ (OpenCode reads
// both natively) and .claude/hooks/ + .claude/permissions.json (.opencode/plugins/sdd.js
// runs them). Other keys of opencode.json are kept: add your OpenCode-only settings there.
//
// Agents: `tools:` becomes `permission:` (a tool the Claude agent lacks is denied; MCP tools
// are an allowlist per server), `model:` an alias mapped by MODELS. OpenCode's task tool takes
// no model per call, so VARIANTS generates `<agent>-<alias>` (e.g. implementer-haiku): the
// plugin gives them their base agent's role in the guard.
//
// Usage: node scripts/sync-opencode.mjs           (writes)
//        node scripts/sync-opencode.mjs --check   (CI: exit 1 if something is stale)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// ── CUSTOMIZE PER PROJECT ────────────────────────────────────────────────────
// Claude alias → OpenCode `provider/model` (`opencode models` lists yours). An alias missing
// here → no `model:` (the agent inherits the session's model).
const MODELS = {
  haiku: "anthropic/claude-haiku-5-5",
  sonnet: "anthropic/claude-sonnet-5-5",
  opus: "anthropic/claude-opus-5-5",
};
// Extra copies of an agent on another model (SKILL «Model per role»): `<agent>-<alias>`.
const VARIANTS = { implementer: ["haiku", "opus"] };
// ─────────────────────────────────────────────────────────────────────────────

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rel = (...p) => path.join(ROOT, ...p);
const read = (p) => (existsSync(rel(p)) ? readFileSync(rel(p), "utf8") : null);
const json = (p) => (read(p) ? JSON.parse(read(p)) : {});
const check = process.argv.includes("--check");

// OpenCode permission key of each Claude tool (several Claude tools share one key).
const KEYS = {
  Read: ["read"], Grep: ["grep"], Glob: ["glob", "list"], Edit: ["edit"], Write: ["edit"],
  MultiEdit: ["edit"], NotebookEdit: ["edit"], Bash: ["bash"], WebFetch: ["webfetch"],
  WebSearch: ["websearch"], Agent: ["task"], Task: ["task"], TodoWrite: ["todowrite"],
  Skill: ["skill"], AskUserQuestion: ["question"], LSP: ["lsp"],
};
const ALL_KEYS = [...new Set(Object.values(KEYS).flat())];

function frontmatter(text, file) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${file}: no frontmatter`);
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].trim();
  }
  return { meta, body: m[2] };
}

const servers = Object.keys(json(".mcp.json").mcpServers ?? {});

function agentFile(name, meta, body, alias) {
  const tools = (meta.tools ?? "").split(",").map((t) => t.trim()).filter(Boolean);
  const perm = {};
  if (tools.length) { // no `tools:` in Claude = every tool, so nothing to deny
    const allowed = new Set(tools.flatMap((t) => KEYS[t] ?? []));
    for (const k of ALL_KEYS) if (!allowed.has(k)) perm[k] = "deny";
    for (const s of servers) {
      perm[`${s}_*`] = "deny"; // last match wins: the agent's own tools are allowed below
      for (const t of tools) {
        const mt = t.match(/^mcp__([^_]+(?:_[^_]+)*)__(.+)$/);
        if (mt && mt[1] === s) perm[`${s}_${mt[2]}`] = "allow";
      }
    }
  }
  const model = MODELS[alias ?? meta.model];
  const src = `.claude/agents/${name}.md`;
  const lines = [
    "---",
    `# GENERATED by scripts/sync-opencode.mjs from ${src}${alias ? ` (on ${alias})` : ""}: edit that one, then run the script.`,
    `description: ${JSON.stringify((alias ? `[${alias}] ` : "") + (meta.description ?? ""))}`,
    "mode: subagent",
    ...(model ? [`model: ${model}`] : []),
    ...(Object.keys(perm).length ? ["permission:", ...Object.entries(perm).map(([k, v]) => `  ${JSON.stringify(k)}: ${v}`)] : []),
    "---",
  ];
  return `${lines.join("\n")}\n${body}`;
}

const want = new Map(); // path → content
for (const f of readdirSync(rel(".claude/agents")).filter((f) => f.endsWith(".md")).sort()) {
  const name = f.replace(/\.md$/, "");
  const { meta, body } = frontmatter(read(`.claude/agents/${f}`), f);
  want.set(`.opencode/agents/${name}.md`, agentFile(name, meta, body));
  for (const alias of VARIANTS[name] ?? []) want.set(`.opencode/agents/${name}-${alias}.md`, agentFile(name, meta, body, alias));
}

// settings.json `deny` → OpenCode `permission` (its last matching rule wins: allow first).
function permission() {
  const out = {};
  for (const rule of json(".claude/settings.json").permissions?.deny ?? []) {
    const m = rule.match(/^(Read|Edit|Write|Bash)\((.*)\)$/);
    if (!m) throw new Error(`settings.json deny «${rule}»: no OpenCode translation (add one here)`);
    const key = m[1] === "Bash" ? "bash" : m[1] === "Read" ? "read" : "edit";
    // Claude paths are `./x` or `./**/x` from the root; OpenCode matches paths relative to it.
    const pat = key === "bash" ? m[2] : m[2].replace(/^\.\//, "").replace(/^\*\*\//, "*/");
    out[key] ??= { "*": "allow" };
    out[key][pat] = "deny";
  }
  return out;
}

function mcp() {
  const out = {};
  for (const [name, s] of Object.entries(json(".mcp.json").mcpServers ?? {})) {
    out[name] = s.url
      ? { type: "remote", url: s.url, ...(s.headers ? { headers: s.headers } : {}), enabled: true }
      : { type: "local", command: [s.command, ...(s.args ?? [])], ...(s.env ? { environment: s.env } : {}), enabled: true };
  }
  return out;
}

const cfg = json("opencode.json");
const merged = { $schema: "https://opencode.ai/config.json", ...cfg, permission: permission(), mcp: mcp() };
want.set("opencode.json", `${JSON.stringify(merged, null, 2)}\n`);

let stale = 0;
for (const [p, content] of want) {
  if (read(p) === content) continue;
  stale++;
  if (check) console.error(`✗ ${p} is stale`);
  else { mkdirSync(path.dirname(rel(p)), { recursive: true }); writeFileSync(rel(p), content); console.log(`· wrote ${p}`); }
}
const dir = ".opencode/agents";
for (const f of existsSync(rel(dir)) ? readdirSync(rel(dir)) : []) {
  if (want.has(`${dir}/${f}`)) continue;
  stale++;
  if (check) console.error(`✗ ${dir}/${f} has no source in .claude/agents/`);
  else { rmSync(rel(dir, f)); console.log(`· removed ${dir}/${f}`); }
}
if (check && stale) {
  console.error(`\n${stale} stale: run  node scripts/sync-opencode.mjs  (sources: .claude/agents, .claude/settings.json, .mcp.json)`);
  process.exit(1);
}
console.log(stale ? `\n${stale} file(s) updated.` : "OpenCode config in sync with Claude Code's.");
